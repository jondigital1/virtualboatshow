/**
 * Convert Jon's Claude Design map SVGs (OneDrive) into lib/showmap.ts:
 * - inject the stacked show logo into the empty <image> placeholders
 * - add Poppins fallbacks after the design fonts
 * - drop fixed width/height from the root so viewBox scales responsively
 * Re-run whenever the source SVGs change.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "C:/Users/jon/OneDrive/Plocha/Virtual Boat Show";

function prep(file) {
  let svg = readFileSync(`${SRC}/${file}`, "utf8");
  svg = svg.replace(/<\?xml[^>]*\?>/, "").trim();
  // scale via viewBox; width 100% comes from the wrapper
  svg = svg.replace(/<svg([^>]*?)\swidth="\d+"\sheight="\d+"/, "<svg$1");
  // empty exported placeholders -> stacked show logo
  svg = svg.replace(/<image (x="[^"]*" y="[^"]*" width="[^"]*" height="[^"]*" preserveAspectRatio="[^"]*")><\/image>/g, '<image $1 href="/ac-logo-stacked.png"></image>');
  // font fallbacks so text stays branded if a Google font is slow/blocked
  svg = svg.replace(/'Barlow Condensed',sans-serif/g, "'Barlow Condensed','Poppins',sans-serif");
  svg = svg.replace(/'Jost',sans-serif/g, "'Jost','Poppins',sans-serif");
  svg = svg.replace(/'Bodoni Moda',serif/g, "'Bodoni Moda',Georgia,serif");
  return svg;
}

const wide = prep("boat-show-map-wide.svg");
const mobile = prep("boat-show-map-mobile.svg");

const out = `/**
 * Official 2026 show map, drawn by Jon in Claude Design (vector, two layouts).
 * Generated by scripts/build-show-map.mjs from the OneDrive source SVGs —
 * edit the sources and re-run, do not hand-edit these strings.
 * Rendered inline (components/ShowMap.tsx) so page fonts and the logo
 * <image> href resolve, and the map stays crisp at any zoom.
 */
export const SHOW_MAP_WIDE = ${JSON.stringify(wide)};
export const SHOW_MAP_MOBILE = ${JSON.stringify(mobile)};
`;
writeFileSync("lib/showmap.ts", out);
console.log("lib/showmap.ts written:", Math.round(wide.length / 1024) + "KB wide,", Math.round(mobile.length / 1024) + "KB mobile");
const missing = (wide + mobile).match(/<image (?![^>]*href)/g);
console.log("placeholders without href remaining:", missing ? missing.length : 0);
